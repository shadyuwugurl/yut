def worlds_matching(tags: set[str], *, allow_nsfw: bool) -> list[dict]:
    pool = [w for w in WORLDS if allow_nsfw or not w.get("nsfw")]
    chosen = [w for w in pool if tags and not tags.isdisjoint(set(w["tags"]))]
    if len(chosen) >= 6:
        return chosen
    for world in pool:
        if "general" in world["tags"] and world not in chosen:
            chosen.append(world)
        if len(chosen) >= 8:
            break
    return chosen or pool
